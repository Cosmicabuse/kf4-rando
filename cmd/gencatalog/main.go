// Command gencatalog turns internal/resources/qol.pnach into
// internal/features/mods/catalog_data.go. Run it after editing qol.pnach.
//
// The analog Y-axis and clamping patches fill gaps in full_analog_controls,
// so they need it. Ladder handling is always on. Widescreen and "Minor
// movement bug fix" are skipped.
package main

import (
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"

	"kf4randomizer/cmd/gencatalog/internal/pnach"
)

const (
	pnachPath  = "internal/resources/qol.pnach"
	outputPath = "internal/features/mods/catalog_data.go"
)

func main() {
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

func run() error {
	raw, err := os.ReadFile(pnachPath)
	if err != nil {
		return fmt.Errorf("reading %s: %w", pnachPath, err)
	}

	sections, err := pnach.Parse(string(raw))
	if err != nil {
		return fmt.Errorf("parsing %s: %w", pnachPath, err)
	}

	byName := make(map[string]pnach.Section, len(sections))
	for _, s := range sections {
		byName[s.Name] = s
	}

	section := func(name string) []pnach.Patch {
		s, ok := byName[name]
		if !ok {
			log.Fatalf("expected section %q not found in %s. Has the file changed? Update this tool's mapping.", name, pnachPath)
		}
		return s.Patches
	}

	var b strings.Builder
	b.WriteString("// Code generated by cmd/gencatalog from resources/qol.pnach. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: go run ./cmd/gencatalog\n\n")
	b.WriteString("package mods\n\n")

	b.WriteString("// AlwaysOnPatches apply whatever mods are picked: ladder handling.\n")
	_, _ = fmt.Fprintf(&b, "var AlwaysOnPatches = []Patch{\n")
	for _, p := range concat(section("Alternative Ladder Handling"), section("Disable looking left/right while on a ladder")) {
		writePatchLiteral(&b, p, "AlwaysOnPatches")
	}
	b.WriteString("}\n\n")

	b.WriteString("// BuiltinCategories is the full QoL patch catalog.\n")
	b.WriteString("var BuiltinCategories = []Category{\n")

	writeCategory(&b, "turn_speed", "Turning speed", []modeSpec{
		{"turn_speed_1_5x", "1.5x turn speed", "", concat(section("1.5x turn speed")), nil},
		{"turn_speed_2x", "2x turn speed", "", concat(section("2x turn speed")), nil},
	})

	writeCategory(&b, "turn_acceleration", "How quickly turning reaches full speed", []modeSpec{
		{"turn_accel_1_5x", "1.5x turn acceleration", "", concat(section("1.5x turn acceleration")), nil},
		{"turn_accel_2x", "2x turn acceleration", "", concat(section("2x turn acceleration")), nil},
		{"turn_accel_3x", "3x turn acceleration", "", concat(section("3x turn acceleration")), nil},
		{"turn_accel_4x", "4x turn acceleration", "", concat(section("4x turn acceleration")), nil},
	})

	writeCategory(&b, "turn_deceleration", "How quickly turning slows back down", []modeSpec{
		{"turn_decel_2x", "2x turn deceleration", "Only impacts how quickly you come to a stop or slow down; may help 2x/4x turn acceleration feel less sluggish.", concat(section("2x turn deceleration")), nil},
	})

	writeCategory(&b, "full_analog_controls", "Full analog stick movement (base patch)", []modeSpec{
		{id: "full_analog_controls", label: "Full analog controls",
			notes:   "Enable full_analog_y_axis separately to choose inverted vs normal Y-axis.",
			patches: concat(section("Full analog controls part 1"), section("Full analog controls part 2"), section("Clamping OFF"))},
	})

	writeCategory(&b, "full_analog_y_axis", "Y-axis direction for full analog controls (requires full_analog_controls)", []modeSpec{
		{id: "full_analog_y_axis_inverted", label: "Inverted Y-axis (pushing down looks up, like a flight stick)",
			notes:    "Requires full_analog_controls to also be enabled.",
			patches:  concat(section("Inverted Y")),
			requires: []string{"full_analog_controls"}},
		{id: "full_analog_y_axis_normal", label: `"Normal" Y-axis (pushing down looks down)`,
			notes:    "Requires full_analog_controls to also be enabled.",
			patches:  concat(section(`"Normal" Y`)),
			requires: []string{"full_analog_controls"}},
	})

	writeCategory(&b, "full_analog_clamping", "Joystick clamping for full analog controls (requires full_analog_controls)", []modeSpec{
		{id: "full_analog_clamping", label: "Enable joystick clamping",
			notes:    "If you experience movement issues with joystick at the corners, enable clamping. Requires full_analog_controls to also be enabled.",
			patches:  concat(section("Clamping ON")),
			requires: []string{"full_analog_controls"}},
	})

	b.WriteString("}\n")

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("formatting generated source: %w", err)
	}

	if err := os.WriteFile(outputPath, formatted, 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", outputPath, err)
	}

	fmt.Printf("Wrote %s\n", outputPath)
	return nil
}

type modeSpec struct {
	id, label, notes string
	patches          []pnach.Patch
	requires         []string
}

// concat keeps section order, composite modes rely on it.
func concat(sections ...[]pnach.Patch) []pnach.Patch {
	var all []pnach.Patch
	for _, s := range sections {
		all = append(all, s...)
	}
	return all
}

func writePatchLiteral(b *strings.Builder, p pnach.Patch, context string) {
	if p.Type != "word" {
		log.Fatalf("%s: unsupported pnach patch type %q at address 0x%08X, only \"word\" patches work", context, p.Type, p.Address)
	}
	_, _ = fmt.Fprintf(b, "\t{Address: 0x%08X, Value: 0x%08X},\n", p.Address, p.Value)
}

func writeCategory(b *strings.Builder, id, description string, specModes []modeSpec) {
	_, _ = fmt.Fprintf(b, "\t{\n\t\tID: %q,\n\t\tDescription: %q,\n\t\tModes: []Mode{\n", id, description)
	for _, m := range specModes {
		_, _ = fmt.Fprintf(b, "\t\t\t{\n\t\t\t\tID: %q,\n\t\t\t\tLabel: %q,\n\t\t\t\tNotes: %q,\n\t\t\t\tPatches: []Patch{\n", m.id, m.label, m.notes)
		for _, p := range m.patches {
			writePatchLiteral(b, p, fmt.Sprintf("mode %q", m.id))
		}
		b.WriteString("\t\t\t\t},\n")
		if len(m.requires) > 0 {
			_, _ = fmt.Fprintf(b, "\t\t\t\tRequires: %#v,\n", m.requires)
		}
		b.WriteString("\t\t\t},\n")
	}
	b.WriteString("\t\t},\n\t},\n")
}
